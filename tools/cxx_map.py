#!/usr/bin/env python3
"""iOS armv7 libstdc++ import names -> VitaSDK libstdc++ (old COW ABI) symbol names.
Only difference on 32-bit ARM: size_t is unsigned long ('m') on iOS, unsigned int ('j') on Vita.
usage: cxx_map.py imports.json out.h"""
import json, sys, subprocess
SKIP_PREFIX = ('___cxa_', '___gxx_', '__Unwind', '__ZSt9terminate', '__ZSt17__throw', '__ZSt19__throw', '__ZSt20__throw',
               '__Znwm', '__Znam', '__ZdlPv', '__ZdaPv', '__ZNSt8ios_base4Init')
KEEP = {'__ZNSo9_M_insertImEERSoT_'}   # really unsigned long (operator<<(unsigned long)), not size_t
SOFT_WRAP = {'__ZNSo9_M_insertIdEERSoT_', '__ZNSo9_M_insertImEERSoT_'}   # implemented in extra_shims.c   # takes a double: softfp guest -> hard-float host needs a wrapper
def conv(name):
    s = name[1:]                # Mach-O leading underscore
    assert s.startswith('_Z'); out = ['_Z']; i = 2
    def num(i):
        j = i
        while s[j].isdigit(): j += 1
        return j
    if s[i] == 'T' and s[i+1] in 'VITS': out.append(s[i:i+2]); i += 2
    elif s[i:i+2] == 'Th':
        j = s.index('_', i) + 1; out.append(s[i:j]); i = j
    elif s[i:i+2] == 'Tv':
        j = s.index('_', i) + 1; j = s.index('_', j) + 1; out.append(s[i:j]); i = j
    while i < len(s):
        c = s[i]
        if c.isdigit():
            j = num(i); n = int(s[i:j]); out.append(s[i:j+n]); i = j + n
        elif c == 'S':
            if s[i+1].isdigit() or s[i+1].isupper() or s[i+1] == '_':
                j = s.index('_', i+1) + 1; out.append(s[i:j]); i = j
            else: out.append(s[i:i+2]); i += 2
        elif c == 'T':
            j = s.index('_', i) + 1; out.append(s[i:j]); i = j
        elif c in 'CD' and i+1 < len(s) and s[i+1].isdigit(): out.append(s[i:i+2]); i += 2
        elif c == 'm': out.append('j'); i += 1
        else: out.append(c); i += 1
    return ''.join(out)
def dem(x): return subprocess.run(['llvm-cxxfilt'], input=x, capture_output=True, text=True).stdout.strip()
imps = json.load(open(sys.argv[1]))
rows = []; bad = 0
for n, v in sorted(imps.items()):
    if not n.startswith('__Z') or n.startswith(SKIP_PREFIX): continue
    h = conv(n) if n not in KEEP else n[1:]
    a = dem(n[1:]); a = a if n in KEEP else a.replace('unsigned long', 'unsigned int'); b = dem(h)
    if a != b: print('MISMATCH', n, h, a, b, file=sys.stderr); bad += 1
    rows.append((n, h, v.get('data', False) if isinstance(v, dict) else False))
with open(sys.argv[2], 'w') as f:
    f.write('/* generated by tools/cxx_map.py: guest (iOS) C++ import -> VitaSDK libstdc++ symbol (old COW std::string ABI) */\n')
    for k, (n, h, d) in enumerate(rows):
        if n in SOFT_WRAP: continue
        f.write(f'extern char cxx_h{k}[] __asm__("{h}");\n')
    f.write('static const struct { const char *guest; void *host; } cxx_map[] = {\n')
    for k, (n, h, d) in enumerate(rows):
        if n in SOFT_WRAP: continue
        f.write(f'    {{"{n}", cxx_h{k}}},\n')
    f.write('};\n')
print(len(rows), 'mapped,', bad, 'mismatches', file=sys.stderr)
