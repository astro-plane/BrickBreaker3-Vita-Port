#!/usr/bin/env python3 -I
"""Analyze a Mach-O armv7 binary: segments, imports (bind + lazy bind), categories.
Emits out/imports.md, out/imports.json, src/binds_gen.h (address->shim table)."""
import subprocess, sys, re, json, collections, os

binpath, outdir, srcdir = sys.argv[1:4]

def run(*a):
    return subprocess.run(['llvm-objdump', '--macho', *a, binpath], capture_output=True, text=True, check=True).stdout

binds = []   # (addr, dylib, symbol, kind)
for kind, flag in (('bind', '--bind'), ('lazy', '--lazy-bind')):
    for ln in run(flag).splitlines():
        m = re.match(r'__DATA\s+(\S+)\s+0x([0-9A-Fa-f]+)\s+(?:\S+\s+\d+\s+)?(\S+)\s+(\S+)$', ln) if kind == 'bind' else \
            re.match(r'__DATA\s+(\S+)\s+0x([0-9A-Fa-f]+)\s+(\S+)\s+(\S+)$', ln)
        if m:
            sec, addr, dylib, sym = m.groups()
            binds.append((int(addr, 16), dylib, sym, kind, sec))

def cat(sym, dylib):
    if sym.startswith('_OBJC_CLASS_$_'): return 'objc-class'
    if sym.startswith('_objc_') or sym.startswith('_OBJC_'): return 'objc-runtime'
    if re.match(r'_gl[A-Z]', sym): return 'gles'
    if sym.startswith('__Z') or sym.startswith('___cxa') or sym.startswith('___gxx') or sym.startswith('__ZT'): return 'c++'
    if dylib in ('libstdc++.6.dylib', 'libgcc_s.1.dylib'): return 'c++/gcc'
    if dylib == 'libSystem.B.dylib': return 'libc/libSystem'
    if sym.startswith('_NS') or sym.startswith('_UI') or sym.startswith('_kEAGL') or sym.startswith('_MP') or sym.startswith('_AV') or sym.startswith('_GK') or sym.startswith('_SK'): return 'apple-const'
    if sym.startswith('_CF') or sym.startswith('_CG') or sym.startswith('_CA'): return 'corefoundation/cg/ca'
    return 'other'

uniq = collections.OrderedDict()
for addr, dylib, sym, kind, sec in binds:
    d = uniq.setdefault(sym, {'dylib': dylib, 'cat': cat(sym, dylib), 'sites': []})
    d['sites'].append((addr, kind, sec))
syms = list(uniq)

# segments
hdr = run('--private-headers')
segs = re.findall(r'segname (\S+)\n\s+vmaddr 0x([0-9a-f]+)\n\s+vmsize 0x([0-9a-f]+)\n\s+fileoff (\d+)\n\s+filesize (\d+)', hdr)
entry = re.search(r'LC_UNIXTHREAD.*?pc 0x([0-9a-f]+)', hdr, re.S)
entry_main = re.search(r'LC_MAIN.*?entryoff (\d+)', hdr, re.S)
inits = re.search(r'sectname __mod_init_func\n\s+segname __DATA\n\s+addr 0x([0-9a-f]+)\n\s+size 0x([0-9a-f]+)', hdr)

by = collections.defaultdict(list)
for s in syms: by[uniq[s]['cat']].append(s)

with open(os.path.join(outdir, 'imports.json'), 'w') as f:
    json.dump({s: {'dylib': v['dylib'], 'cat': v['cat'], 'sites': [hex(a[0]) for a in v['sites']]} for s, v in uniq.items()}, f, indent=1)

with open(os.path.join(outdir, 'imports.md'), 'w') as f:
    f.write('# BAROQUE imports\n\n')
    f.write(f'Total unique imported symbols: **{len(syms)}** ({len(binds)} bind sites)\n\n')
    f.write('| Category | Count |\n|---|---|\n')
    for c, l in sorted(by.items(), key=lambda x: -len(x[1])): f.write(f'| {c} | {len(l)} |\n')
    f.write('\n## Segments\n\n| name | vmaddr | vmsize | fileoff | filesize |\n|---|---|---|---|---|\n')
    for n, a, vs, fo, fs in segs: f.write(f'| {n} | 0x{a} | 0x{vs} | {fo} | {fs} |\n')
    f.write(f'\nEntry (LC_UNIXTHREAD pc): {entry.group(1) if entry else None}; LC_MAIN entryoff: {entry_main.group(1) if entry_main else None}\n')
    if inits: f.write(f'__mod_init_func: addr 0x{inits.group(1)} size 0x{inits.group(2)} ({int(inits.group(2),16)//4} initializers)\n')
    for c, l in sorted(by.items(), key=lambda x: -len(x[1])):
        f.write(f'\n## {c} ({len(l)})\n\n')
        f.write(', '.join(f'`{s}`' for s in l) + '\n')

# generated C header: table of import names, and bind sites referencing index
with open(os.path.join(srcdir, 'binds_gen.h'), 'w') as f:
    f.write('/* generated by tools/analyze.py - do not edit */\n')
    f.write(f'#define N_IMPORTS {len(syms)}\n')
    f.write('static const char *const import_names[N_IMPORTS] = {\n')
    for s in syms: f.write(f'  "{s}",\n')
    f.write('};\nstatic const char *const import_cats[N_IMPORTS] = {\n')
    for s in syms: f.write(f'  "{uniq[s]["cat"]}",\n')
    f.write('};\n/* 1 = data symbol (slot holds a pointer to storage), 0 = function */\nstatic const unsigned char import_is_data[N_IMPORTS] = {\n')
    DATA=('_OBJC_','__OBJC','_k','___std','__Default','__NSConcrete','___CFConstant','__objc_empty','_MPMovie')
    for s in syms: f.write('  %d,\n' % (1 if s.startswith(DATA) else 0))
    f.write('};\ntypedef struct { unsigned addr; unsigned short idx; unsigned char lazy; } bind_site_t;\n')
    sites = sorted((a, i, 1 if k == 'lazy' else 0) for i, s in enumerate(syms) for a, k, _ in uniq[s]['sites'])
    f.write(f'#define N_BIND_SITES {len(sites)}\nstatic const bind_site_t bind_sites[N_BIND_SITES] = {{\n')
    for a, i, l in sites: f.write(f'  {{0x{a:x},{i},{l}}},\n')
    f.write('};\n')
print(len(syms), 'imports,', len(binds), 'sites'); print({c: len(l) for c, l in by.items()})

with open(os.path.join(srcdir, 'stubs_gen.h'), 'w') as f:
    f.write('/* generated: one logging stub per import; replace by real shims in shims.c */\n')
    for i in range(len(syms)): f.write(f'static int stub_{i}(void){{ return missing_import2({i}, __builtin_return_address(0)); }}\n')
    f.write('static void *const stub_table[N_IMPORTS] = {\n')
    for i in range(len(syms)): f.write(f'  (void*)stub_{i},\n')
    f.write('};\n')

